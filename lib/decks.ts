export const TOTAL_CARDS = DECKS.reduce((n, d) => n + d.cards.length, 0);

/** 正面 → 卡组 id。卡片本身不存组别，靠正面反查即可。 */
const FRONT_TO_DECK = new Map<string, string>(
  DECKS.flatMap((d) => d.cards.map(([front]) => [front, d.id] as [string, string])),
);

export function deckOfFront(front: string): string | undefined {
  return FRONT_TO_DECK.get(front);
}

export function deckById(id: string): Deck | undefined {
  return DECKS.find((d) => d.id === id);
}
